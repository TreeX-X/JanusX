import { expect, test, type Page } from '@playwright/test'

const state = (page: Page) => page.evaluate(() => (window as any).extensionFixture.state())
const example = (page: Page, location: 'workspace' | 'right') => page.locator(`[data-extension-example="${location}"]:visible`)

for (const theme of ['planche', 'dark']) {
  test(`registers both positions, shares project state and isolates projects (${theme})`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto(`/extensions.html?theme=${theme}`)
    await expect(example(page, 'workspace')).toContainText('Application · 0')
    await page.getByRole('button', { name: 'Example inspector', exact: false }).click()
    await expect(example(page, 'right')).toContainText('one · 0')
    await example(page, 'right').getByRole('button', { name: 'Increment', exact: true }).click()
    await example(page, 'right').getByRole('button', { name: 'Open project view' }).click()
    await expect(example(page, 'workspace')).toContainText('one · 1')
    await example(page, 'workspace').getByRole('button', { name: 'Increment', exact: true }).click()
    await expect(example(page, 'right')).toContainText('one · 2')
    await page.getByRole('button', { name: 'Project two', exact: true }).click()
    await expect(example(page, 'right')).toContainText('two · 0')
    await expect(example(page, 'workspace')).toContainText('Application · 0')
    await example(page, 'right').getByRole('button', { name: 'Open project view' }).click()
    await expect(example(page, 'workspace')).toContainText('two · 0')
    await page.getByRole('button', { name: 'Project one', exact: true }).click()
    await expect(example(page, 'right')).toContainText('one · 2')
    await expect(example(page, 'workspace')).toContainText('one · 2')
    expect((await state(page)).tabs.filter((tab: any) => tab.scope === 'application')).toHaveLength(1)
    expect(errors).toEqual([])
  })
}

test('opens registered workspace views from the existing menu and closes without disabling', async ({ page }) => {
  await page.goto('/extensions.html')
  await page.getByRole('button', { name: 'New Terminal', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Example project', exact: true }).click()
  await expect(example(page, 'workspace')).toContainText('one · 0')
  const tab = page.locator('[data-tab-id*="/project:"]')
  await tab.hover()
  await tab.locator('[data-tab-close]').click()
  await expect(example(page, 'workspace')).toContainText('Application · 0')
  expect((await state(page)).activations).toBe(1)
  expect((await state(page)).disposals).toBe(0)
})

test('disable and unregister remove entries, views, inactive snapshots and owned resources', async ({ page }) => {
  await page.goto('/extensions.html')
  await page.getByRole('button', { name: 'Example inspector', exact: false }).click()
  await example(page, 'right').getByRole('button', { name: 'Open project view' }).click()
  await page.getByRole('button', { name: 'Project two', exact: true }).click()
  await page.getByRole('button', { name: 'Disable example' }).click()
  await expect(page.locator('[data-extension-example]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Example inspector', exact: false })).toHaveCount(0)
  await expect.poll(async () => { const result = await state(page); return result.mounts - result.unmounts }).toBe(0)
  const disabled = await state(page)
  expect(disabled.tabs).toEqual([])
  expect(disabled.right).toEqual([])
  expect(disabled.snapshots.one.paneTree).toBeNull()
  expect(disabled.disposals).toBe(1)
  await page.getByRole('button', { name: 'Enable example' }).click()
  await expect(page.getByRole('button', { name: 'Example inspector', exact: false })).toBeVisible()
  await expect(page.locator('[data-extension-example]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open overview' }).click()
  await expect(example(page, 'workspace')).toContainText('Application · 0')
  await page.getByRole('button', { name: 'Unregister example' }).click()
  await expect(page.locator('[data-extension-example]')).toHaveCount(0)
  expect((await state(page)).disposals).toBe(2)
})

test('a failed extension view is isolated from other views', async ({ page }) => {
  await page.goto('/extensions.html')
  await page.getByRole('button', { name: 'Broken view', exact: false }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.evaluate(() => (window as any).extensionFixture.recoverBrokenView())
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByText('Recovered view', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await example(page, 'workspace').getByRole('button', { name: 'Increment', exact: true }).click()
  await expect(example(page, 'workspace')).toContainText('Application · 1')
  await page.getByRole('button', { name: 'Example inspector', exact: false }).click()
  await expect(example(page, 'right')).toContainText('one · 0')
})
