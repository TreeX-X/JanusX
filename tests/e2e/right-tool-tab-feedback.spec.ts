import { expect, test } from '@playwright/test'

for (const theme of ['planche', 'dark']) {
  test(`tab feedback precedes activation and reversals coalesce in ${theme}`, async ({ page }) => {
    await page.clock.install({ time: new Date('2026-10-19T00:00:00Z') })
    await page.goto(`/tool-palette.html?theme=${theme}`)
    await expect(page.locator('#right-tool-panel-files').getByText('README.md', { exact: true })).toBeVisible()
    await page.clock.pauseAt(new Date('2026-10-19T00:01:00Z'))
    const git = page.locator('#right-tool-tab-git')
    const sessions = page.locator('#right-tool-tab-sessions')
    const tabs = page.getByRole('tablist')
    const marker = page.getByTestId('right-tool-tab-indicator')
    const initialX = await marker.evaluate((element) => element.getBoundingClientRect().x)
    await git.dispatchEvent('click')
    await page.clock.runFor(32)
    await expect(git).toHaveAttribute('data-pending', 'true')
    await expect(git).toHaveAttribute('aria-selected', 'false')
    await expect(tabs).toHaveAttribute('aria-busy', 'true')
    await expect(page.locator('#right-tool-panel-files')).toBeVisible()
    // Playwright's clock controls JS timers; CSS transitions use real frames.
    await expect.poll(() => marker.evaluate((element) => element.getBoundingClientRect().x)).toBeGreaterThan(initialX)
    for (const tool of ['sessions', 'git', 'sessions']) {
      await page.locator(`#right-tool-tab-${tool}`).dispatchEvent('click')
      await page.clock.runFor(32)
    }
    await page.clock.runFor(160)
    await expect(sessions).toHaveAttribute('aria-selected', 'true')
    await expect(tabs).toHaveAttribute('aria-busy', 'false')
    await expect(page.getByRole('tabpanel')).toHaveCount(1)
    const state = await page.evaluate(() => (window as any).builtinExtensionFixture.state())
    expect(state.toolActivations).toEqual(['sessions'])
    expect(state.listeners).toBe(2)
    // The same shared marker ends exactly beneath the destination tab.
    const targetBox = (await sessions.boundingBox())!
    await expect.poll(async () => Math.abs((await marker.boundingBox())!.x - (await sessions.boundingBox())!.x)).toBeLessThan(0.5)
    const markerBox = (await marker.boundingBox())!
    expect(markerBox.x).toBeCloseTo(targetBox.x, 0)
    expect(markerBox.width).toBeCloseTo(targetBox.width, 0)
    await page.screenshot({ path: test.info().outputPath(`tab-feedback-${theme}.png`) })
  })
}

test('pending switches cancel on reversal, close and dock collapse', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-19T00:00:00Z') })
  await page.goto('/tool-palette.html')
  await expect(page.locator('#right-tool-panel-files').getByText('README.md', { exact: true })).toBeVisible()
  await page.clock.pauseAt(new Date('2026-10-19T00:01:00Z'))
  const files = page.locator('#right-tool-tab-files')
  const git = page.locator('#right-tool-tab-git')
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await files.dispatchEvent('click')
  await page.clock.runFor(200)
  await expect(files).toHaveAttribute('aria-selected', 'true')
  await git.dispatchEvent('click')
  await page.clock.runFor(32)
  await git.getByRole('button').dispatchEvent('click')
  await page.clock.runFor(200)
  await expect(git).toHaveCount(0)
  await expect(files).toHaveAttribute('aria-selected', 'true')
  await page.locator('#right-tool-tab-sessions').dispatchEvent('click')
  await page.clock.runFor(32)
  await page.getByRole('button', { name: '折叠右侧工具面板', exact: true }).dispatchEvent('click')
  await page.clock.runFor(500)
  await expect(page.getByRole('tabpanel')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).builtinExtensionFixture.state().toolActivations)).toEqual([])
})

test('keyboard activation stays responsive and reduced motion disables marker sliding', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tool-palette.html')
  const files = page.locator('#right-tool-tab-files')
  await expect(files).toHaveAttribute('aria-selected', 'true')
  await files.focus()
  await page.keyboard.press('End')
  const sessions = page.locator('#right-tool-tab-sessions')
  await expect(sessions).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(sessions).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByTestId('right-tool-tab-indicator')).toHaveCSS('transition-duration', '0s')
  await sessions.getByRole('button').focus()
  await page.keyboard.press('Enter')
  await expect(sessions).toHaveCount(0)
})
