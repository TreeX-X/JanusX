import { expect, test } from '@playwright/test'

test('manages memo as a confirmed preview and preserves data and binding across disabling', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/memo.html?settings=1')
  const settings = page.getByTestId('experimental-settings')
  const toggle = settings.getByRole('checkbox', { name: 'Memo', exact: true })
  await expect(toggle).toBeEnabled()
  await expect(toggle).not.toBeChecked()
  await expect(settings.locator('section').filter({ has: page.getByRole('heading', { name: 'Preview · Preview Features' }) }).getByRole('checkbox', { name: 'Memo', exact: true })).toBeVisible()
  const trigger = page.getByRole('button', { name: 'Open memo on the left' })
  await expect(trigger).toHaveCount(0)

  await toggle.press('Space')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(toggle).not.toBeChecked()
  await expect(trigger).toHaveCount(0)
  await toggle.press('Space')
  await page.getByRole('button', { name: 'Enable feature', exact: true }).click()
  await expect(trigger).toBeVisible()
  await page.evaluate(() => (window as any).memoFixture.bind('00000000-0000-4000-8000-000000000001'))
  await trigger.click()
  await expect(page.locator('.memo-panel')).toBeVisible()
  const before = await page.evaluate(() => JSON.stringify((window as any).memoFixture.memos))
  await page.evaluate(() => (window as any).memoFixture.send('Read this memo'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.requests.length)).toBe(1)

  await toggle.press('Space')
  await page.getByRole('button', { name: 'Disable feature', exact: true }).click()
  await expect(trigger).toHaveCount(0)
  await expect(page.locator('.memo-panel')).toHaveCount(0)
  expect(await page.evaluate(() => (window as any).memoFixture.aborted)).toBe(0)
  expect(await page.evaluate(() => JSON.stringify((window as any).memoFixture.memos))).toBe(before)
  await page.evaluate(() => (window as any).memoFixture.finish())
  await expect(page.locator('main.janus-chat')).toHaveAttribute('data-streaming', 'false')
  await page.evaluate(() => (window as any).memoFixture.send('Continue ordinary chat'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.requests.length)).toBe(2)
  expect(await page.evaluate(() => {
    const request = (window as any).memoFixture.requests.at(-1)
    return { binding: request.memoBinding ?? null, message: request.memoMessageId ?? null }
  })).toEqual({ binding: null, message: null })
  await page.evaluate(() => (window as any).memoFixture.finish())

  await toggle.press('Space')
  await page.getByRole('button', { name: 'Enable feature', exact: true }).click()
  await trigger.click()
  await expect(page.locator('.memo-panel')).toBeVisible()
  await page.evaluate(() => (window as any).memoFixture.send('Read the memo again'))
  await expect.poll(() => page.evaluate(() => (window as any).memoFixture.requests.length)).toBe(3)
  expect(await page.evaluate(() => (window as any).memoFixture.requests.at(-1).memoBinding.memoId)).toBe('00000000-0000-4000-8000-000000000001')
})
