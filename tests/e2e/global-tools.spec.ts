import { expect, test, type Page } from '@playwright/test'

const state = (page: Page) => page.evaluate(() => (window as any).toolsFixture.state())
const region = (page: Page, name: string) => page.locator(`[data-pane-region="${name}"]`)
async function drag(page: Page, id: string, target: string, x: number, y: number) {
  const source = await page.locator(`[data-tab-id="${id}"]`).boundingBox()
  const destination = await page.locator(target).boundingBox()
  if (!source || !destination) throw Error('Missing drag target')
  await page.mouse.move(source.x + 30, source.y + 15)
  await page.mouse.down()
  await page.mouse.move(source.x + 40, source.y + 15)
  await expect(page.locator('[data-tab-drag-clone]')).toHaveCount(1)
  await page.mouse.move(destination.x + destination.width * x, destination.y + destination.height * y, { steps: 10 })
  await page.mouse.up()
  await expect(page.locator('[data-tab-drag-clone]')).toHaveCount(0)
}

test('switching projects retains global browser ownership and nested split ratios', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/global-tools.html')
  await expect.poll(async () => (await state(page)).bounds.at(-1)?.width ?? 0).toBeGreaterThan(0)
  const browserNode = await page.locator('[data-tab-id="browser:browser"]').elementHandle()
  const before = await state(page)
  await page.evaluate(() => (window as any).toolsFixture.clearBounds())
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  await expect(region(page, 'project').locator('[data-tab-id="terminal:B-2"]')).toBeVisible()
  expect((await state(page)).project.ratio).toBe(.35)
  expect((await state(page)).tools).toEqual(before.tools)
  expect(await browserNode!.evaluate((element) => element.isConnected)).toBe(true)
  expect((await state(page)).bounds.every((bounds: any) => bounds.width > 0)).toBe(true)
  const separator = page.getByRole('separator', { name: 'Resize project and tools' })
  await separator.focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(async () => (await state(page)).ratio).toBeCloseTo(.57)
  await page.getByRole('button', { name: 'Project A', exact: true }).click()
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  expect((await state(page)).ratio).toBeCloseTo(.57)
  expect((await state(page)).project.ratio).toBe(.35)
  await page.screenshot({ path: test.info().outputPath('global-tools-planche.png') })
  await page.getByRole('button', { name: 'Project Empty', exact: true }).click()
  await expect(region(page, 'tools').locator('[data-tab-id="browser:browser"]')).toBeVisible()
  await page.getByRole('button', { name: 'No project', exact: true }).click()
  await expect(region(page, 'project')).toBeHidden()
  await expect(region(page, 'tools')).toBeVisible()
  expect(errors).toEqual([])
})

test('compact mode hides native guests and reopens tools without destroying project splits', async ({ page }) => {
  await page.goto('/global-tools.html?theme=dark')
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  const project = (await state(page)).project
  await page.setViewportSize({ width: 520, height: 720 })
  await expect(page.getByRole('button', { name: 'Show tools', exact: true })).toBeVisible()
  await expect(region(page, 'tools')).toBeHidden()
  await expect.poll(async () => (await state(page)).bounds.at(-1)?.width).toBe(0)
  await page.getByRole('button', { name: 'Show tools', exact: true }).click()
  await expect(region(page, 'tools')).toBeVisible()
  await expect(region(page, 'project')).toBeHidden()
  await expect.poll(async () => (await state(page)).bounds.at(-1)?.width ?? 0).toBeGreaterThan(0)
  await page.screenshot({ path: test.info().outputPath('global-tools-compact.png') })
  await page.getByRole('button', { name: 'Collapse tools', exact: true }).click()
  expect((await state(page)).project).toEqual(project)
  await page.locator('[data-id="tool-menu"]').click()
  const entry = page.locator('[role="menuitem"][data-id="browser"]')
  await expect(entry).toBeEnabled()
  await entry.click()
  await expect(region(page, 'tools')).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 720 })
  await expect(region(page, 'project')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('global-tools-dark.png') })
  expect((await state(page)).project).toEqual(project)
})

test('Markdown selection remains stable and tools split only within their own region', async ({ page }) => {
  await page.goto('/global-tools.html')
  await page.locator('[data-tab-id="markdown:global-markdown"]').click()
  await expect(page.getByRole('combobox', { name: 'Draft source' })).toHaveValue('A')
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Draft source' })).toHaveValue('A')
  await expect(page.getByRole('textbox', { name: 'Note title', exact: true })).toHaveValue('Project A notes')
  await expect(page.getByRole('textbox', { name: 'Note content', exact: true })).toHaveValue('Document from project A')
  const before = await state(page)
  await drag(page, 'browser:browser', '[data-pane-region="project"]', .5, .5)
  expect((await state(page)).tools).toEqual(before.tools)
  expect((await state(page)).project).toEqual(before.project)
  await drag(page, 'browser:browser', '[data-pane-region="tools"] [data-pane-id]', .5, .97)
  await expect(region(page, 'tools').locator('[data-pane-id]')).toHaveCount(2)
  expect((await state(page)).project).toEqual(before.project)
  await page.getByRole('combobox', { name: 'Draft source' }).selectOption('B')
  expect((await state(page)).scope).toBe('B')
})

test('outer pointer resize and compact project navigation preserve the nested tree', async ({ page }) => {
  await page.goto('/global-tools.html')
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  const before = (await state(page)).project
  const separator = page.getByRole('separator', { name: 'Resize project and tools' })
  const box = await separator.boundingBox()
  const layout = await page.locator('[data-global-tools-layout]').boundingBox()
  if (!box || !layout) throw Error('Missing outer split')
  await page.mouse.move(box.x + box.width / 2, box.y + 150)
  await page.mouse.down()
  await page.mouse.move(layout.x + (layout.width - 9) * .7 + 4.5, box.y + 150, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => (await state(page)).ratio).toBeCloseTo(.7, 2)
  await separator.focus()
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await expect(separator).toBeFocused()
  await expect.poll(async () => (await state(page)).ratio).toBeCloseTo(.6, 2)
  await page.keyboard.press('Home')
  await expect(separator).toBeVisible()
  await page.keyboard.press('End')
  await expect(separator).toBeVisible()
  await expect(separator).toBeFocused()
  expect((await state(page)).project).toEqual(before)
  await page.setViewportSize({ width: 520, height: 720 })
  await page.getByRole('button', { name: 'Show tools', exact: true }).click()
  await page.getByRole('button', { name: 'Project A', exact: true }).click()
  await expect(region(page, 'tools')).toBeHidden()
  await expect(region(page, 'project').locator('[data-tab-id="terminal:A-1"]')).toBeVisible()
  await page.getByRole('button', { name: 'Project B', exact: true }).click()
  expect((await state(page)).project).toEqual(before)
  await page.getByRole('button', { name: 'Show tools', exact: true }).click()
  await page.evaluate(() => (window as any).toolsFixture.selectTerminal('B-1'))
  await expect(region(page, 'tools')).toBeHidden()
  await expect(region(page, 'project').locator('[data-tab-id="terminal:B-1"]')).toBeVisible()
})
