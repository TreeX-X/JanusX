test('select menus stay inside a short viewport', async ({ page }) => {
  await page.setViewportSize({ width: 640, height: 420 })
  await page.goto('/settings.html?tab=llm&en')
  await page.getByRole('button', { name: 'Channel', exact: true }).click()
  const bounds = await page.locator('[data-select-dropdown]').boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(640)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(420)
  await page.getByRole('option', { name: 'CPA Work', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Channel', exact: true })).toContainText('CPA Work')
})

