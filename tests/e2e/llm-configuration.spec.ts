test('editing a shared channel marks its external Agents as needing reapplication', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en')
  await page.getByRole('button', { name: /^Pi / }).click()
  await choose(page, 'Channel', 'CPA Work')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await page.getByRole('tab', { name: /Channels/ }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Channel name', exact: true }).fill('CPA Rotated')
  await page.getByRole('button', { name: 'Save channel', exact: true }).click()
  await page.getByRole('tab', { name: /Agents/ }).click()
  await expect(page.getByRole('button', { name: /^Pi / })).toContainText('Apply needed')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Pi / })).not.toContainText('Apply needed')
})

