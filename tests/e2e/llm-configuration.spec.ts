import { expect, test, type Page } from '@playwright/test'

async function choose(page: Page, field: string, option: string) {
  await page.getByRole('button', { name: field, exact: true }).scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: field, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}
test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test('one channel serves multiple Agents with independent models and distinct channel labels', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en')
  await choose(page, 'Channel', 'CPA Work')
  await page.getByLabel('Model', { exact: true }).fill('gpt-4.1')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /Janus.*gpt-4.1 · CPA Work/ })).toBeVisible()
  await page.getByRole('button', { name: /^Pi / }).click()
  await choose(page, 'Channel', 'CPA Work')
  await page.getByLabel('Model', { exact: true }).fill('gpt-4o')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /Pi.*gpt-4o · CPA Work/ })).toBeVisible()
  await page.getByRole('button', { name: /^Codex / }).click()
  await page.getByRole('button', { name: 'Channel', exact: true }).click()
  await expect(page.getByRole('option', { name: 'CPA Work · Incompatible protocol', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await page.getByRole('option', { name: 'OpenAI Official', exact: true }).click()
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /Codex.*gpt-4.1 · OpenAI Official/ })).toBeVisible()
  await choose(page, 'Channel', 'Native settings / official sign-in')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Codex / })).toContainText('Native settings / official sign-in')
})

test('creates an official channel once, tests it, and protects channels in use', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en&empty')
  await page.getByRole('tab', { name: /Channels/ }).click()
  await page.getByRole('button', { name: 'Add channel', exact: true }).click()
  await choose(page, 'Service preset', 'OpenAI · Official API')
  await expect(page.getByRole('textbox', { name: 'API endpoint', exact: true })).toHaveValue('https://api.openai.com/v1')
  await page.getByRole('textbox', { name: 'Channel name', exact: true }).fill('OpenAI Personal')
  await page.getByLabel('API key', { exact: true }).fill('sk-fixture-1234567890')
  await expect(page.getByLabel('API key', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByRole('textbox', { name: 'Available models', exact: true }).fill('gpt-4.1\ngpt-4o')
  await page.getByRole('button', { name: 'Test connection', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Connected')
  await page.getByRole('button', { name: 'Save channel', exact: true }).click()
  await expect(page.getByText('OpenAI Personal', { exact: true })).toBeVisible()
  await expect(page.getByText('Official API', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: /Agents/ }).click()
  await choose(page, 'Channel', 'OpenAI Personal')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await page.getByRole('tab', { name: /Channels/ }).click()
  await expect(page.getByRole('button', { name: 'Delete channel OpenAI Personal', exact: true })).toBeDisabled()
})

test('failed writes preserve the selected draft and saved Agent configuration', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en&applyFail')
  await choose(page, 'Channel', 'CPA Work')
  await page.getByLabel('Model', { exact: true }).fill('custom-model')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Fixture connection write failed')
  await expect(page.getByLabel('Model', { exact: true })).toHaveValue('custom-model')
  await expect(page.getByRole('button', { name: /^Janus / })).toContainText('Not configured')
  await page.getByRole('tab', { name: /Channels/ }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Channel name', exact: true }).fill('Draft retained')
  await page.getByRole('tab', { name: /Agents/ }).click()
  await page.getByRole('tab', { name: /Channels/ }).click()
  await expect(page.getByRole('textbox', { name: 'Channel name', exact: true })).toHaveValue('Draft retained')
})

test('channel save failures retain the editor draft', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en&saveFail')
  await page.getByRole('tab', { name: /Channels/ }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Channel name', exact: true }).fill('Unsaved channel')
  await page.getByRole('button', { name: 'Save channel', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Fixture channel save failed')
  await expect(page.getByRole('textbox', { name: 'Channel name', exact: true })).toHaveValue('Unsaved channel')
  await expect(page.getByRole('button', { name: 'Save channel', exact: true })).toBeEnabled()
})

test('editing a shared channel marks its external Agents as needing reapplication', async ({ page }) => {
  await page.goto('/settings.html?tab=llm&en')
  await page.getByRole('button', { name: /^Pi / }).click()
  await choose(page, 'Channel', 'CPA Work')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await page.getByRole('tab', { name: /Channels/ }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Channel name', exact: true }).fill('CPA Rotated')
  await page.getByRole('button', { name: 'Save channel', exact: true }).click()
  await page.getByRole('tab', { name: /Agents/ }).click()
  await expect(page.getByRole('button', { name: /^Pi / })).toContainText('Apply needed')
  await page.getByRole('button', { name: 'Apply configuration', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Pi / })).not.toContainText('Apply needed')
})

