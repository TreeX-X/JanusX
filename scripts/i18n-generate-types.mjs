#!/usr/bin/env node
/**
 * i18n type generation: scans locale JSON files and emits a TypeScript
 * type literal mapping every fully-qualified key (`namespace:dot.path`) to
 * `string`. Run after `i18n:extract` to keep types in sync.
 *
 * Output: src/renderer/src/i18n/types.ts
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const LOCALES_DIR = join(__dirname, '..', 'src', 'renderer', 'src', 'i18n', 'locales')
const OUTPUT_FILE = join(__dirname, '..', 'src', 'renderer', 'src', 'i18n', 'types.ts')
const SOURCE_LANG = 'zh-CN'

function flattenKeys(obj, prefix = '') {
  const keys = []
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      keys.push(...flattenKeys(value, path))
    } else {
      keys.push(path)
    }
  }
  return keys
}

async function main() {
  const namespaces = await readdir(join(LOCALES_DIR, SOURCE_LANG))
  const allKeys = []

  for (const file of namespaces) {
    if (!file.endsWith('.json')) continue
    const ns = file.slice(0, -5)
    const raw = await readFile(join(LOCALES_DIR, SOURCE_LANG, file), 'utf8')
    let parsed
    try {
      parsed = JSON.parse(raw)
    } catch {
      console.warn(`[i18n:types] skipping malformed ${file}`)
      continue
    }
    for (const key of flattenKeys(parsed)) {
      allKeys.push(`'${ns}:${key}'`)
    }
  }

  allKeys.sort()
  const header = `// AUTO-GENERATED by scripts/i18n-generate-types.mjs — do not edit by hand.
// Regenerate via \`npm run i18n:types\` after changing locale JSON files.

`
  const body = allKeys.length === 0
    ? 'export type TypedI18nKey = never\n'
    : `export type TypedI18nKey =\n${allKeys.map((k) => `  | ${k}`).join('\n')}\n`

  await mkdir(dirname(OUTPUT_FILE), { recursive: true })
  await writeFile(OUTPUT_FILE, header + body, 'utf8')
  console.log(`[i18n:types] wrote ${allKeys.length} keys to ${OUTPUT_FILE}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})